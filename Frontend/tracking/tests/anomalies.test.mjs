// @vitest-environment jsdom
import {afterEach,expect,it,vi} from 'vitest';
import {createAnomalyNotice} from '../anomalies.mjs';
afterEach(()=>vi.useRealTimers());
it('turns green and replaces the button with text for five seconds, then dismisses the episode',()=>{
 vi.useFakeTimers();
 const container=document.createElement('aside'),notice=createAnomalyNotice(container);
 const ship=age=>({id:'one',name:'Vessel',age_minutes:age});
 notice.update([ship(16)],'C');
 const button=container.querySelector('button.anomaly-note'),confirmation=container.querySelector('[role=status]');
 button.click();
 expect(button.hidden).toBe(true);
 expect(confirmation.hidden).toBe(false);
 expect(confirmation.textContent).toBe('Added to training data');
 expect(container.classList.contains('is-confirmed')).toBe(true);
 notice.update([ship(17)],'C');
 vi.advanceTimersByTime(4999);
 expect(container.hidden).toBe(false);
 expect(confirmation.hidden).toBe(false);
 vi.advanceTimersByTime(1);
 expect(container.classList.contains('is-leaving')).toBe(true);
 expect(container.hidden).toBe(false);
 notice.update([ship(18)],'C');
 expect(container.classList.contains('is-leaving')).toBe(true);
 vi.advanceTimersByTime(419);
 expect(container.hidden).toBe(false);
 vi.advanceTimersByTime(1);
 expect(container.hidden).toBe(true);
 notice.update([ship(18)],'C');
 expect(container.hidden).toBe(true);
 notice.update([],'C');notice.update([ship(19)],'C');
 expect(container.hidden).toBe(false);
 expect(button.hidden).toBe(false);
 expect(confirmation.hidden).toBe(true);
 expect(container.classList.contains('is-confirmed')).toBe(false);
});
it('cancels the dismissal timer on reset',()=>{
 vi.useFakeTimers();
 const container=document.createElement('aside'),notice=createAnomalyNotice(container);
 const ships=[{id:'one',name:'Vessel',age_minutes:20}];
 notice.update(ships,'C');container.querySelector('button.anomaly-note').click();
 vi.advanceTimersByTime(5000);
 expect(container.classList.contains('is-leaving')).toBe(true);
 notice.reset();notice.update(ships,'C');vi.advanceTimersByTime(5420);
 expect(container.classList.contains('is-leaving')).toBe(false);
 expect(container.classList.contains('is-confirmed')).toBe(false);
 expect(container.hidden).toBe(false);
 expect(container.querySelector('button.anomaly-note').hidden).toBe(false);
});
